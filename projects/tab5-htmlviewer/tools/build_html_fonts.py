#!/usr/bin/env python3
"""Generate the embedded, subsetted OFL font atlas for Tab5 HTML Viewer.

The source fonts are vendored under third_party/fonts so regeneration does not
depend on host-installed proprietary fonts.
"""
from pathlib import Path

from ttf_subset import subset_ttf

PROJECT = Path(__file__).resolve().parents[1]
FONT_DIR = PROJECT / "third_party" / "fonts"
OUTPUT = PROJECT / "firmware" / "main" / "fonts" / "embedded_html_fonts.h"

TARGET_CPS = (
    set(range(0x20, 0x7F))
    | set(range(0xA0, 0x100))
    | {
        0x2010, 0x2011, 0x2012, 0x2013, 0x2014, 0x2015,
        0x2018, 0x2019, 0x201A, 0x201C, 0x201D, 0x201E,
        0x2020, 0x2021, 0x2022, 0x2026, 0x2030, 0x2032, 0x2033, 0x2039, 0x203A,
        0x20AC, 0x2122, 0x2190, 0x2191, 0x2192, 0x2193, 0x2194,
        0x2212, 0x221A, 0x221E, 0x2248, 0x2260, 0x2264, 0x2265,
        0x25A0, 0x25A1, 0x25AA, 0x25AB, 0x25B2, 0x25B6, 0x25BC, 0x25C0, 0x25CF, 0x25CB,
    }
)

FONTS = {
    "kSourceSansRegularTtf": "SourceSans3-Regular.ttf",
    "kSourceSansBoldTtf": "SourceSans3-Bold.ttf",
    "kSourceSansItalicTtf": "SourceSans3-It.ttf",
    "kSourceSansBoldItalicTtf": "SourceSans3-BoldIt.ttf",
    "kSourceSerifRegularTtf": "SourceSerif4-Regular.ttf",
    "kSourceSerifBoldTtf": "SourceSerif4-Bold.ttf",
    "kSourceSerifItalicTtf": "SourceSerif4-It.ttf",
    "kSourceSerifBoldItalicTtf": "SourceSerif4-BoldIt.ttf",
    "kSourceCodeRegularTtf": "SourceCodePro-Regular.ttf",
    "kSourceCodeBoldTtf": "SourceCodePro-Bold.ttf",
}


def format_c_array(name: str, data: bytes) -> str:
    lines = [f"alignas(4) inline constexpr uint8_t {name}[{len(data)}] = {{"]
    for offset in range(0, len(data), 16):
        chunk = data[offset : offset + 16]
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    lines.extend(["};", f"inline constexpr size_t {name}Size = {len(data)};\n"])
    return "\n".join(lines)


def main() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    parts = [
        "#pragma once",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "// Generated by tools/build_html_fonts.py from OFL-licensed Adobe fonts.",
        "namespace tab5_html_fonts {",
        "",
    ]
    total = 0
    for variable, filename in FONTS.items():
        source = FONT_DIR / filename
        if not source.is_file():
            raise SystemExit(f"Missing font source: {source}")
        subset = subset_ttf(source.read_bytes(), TARGET_CPS)
        total += len(subset)
        parts.append(format_c_array(variable, subset))
    parts.extend(["}", ""])
    OUTPUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"Wrote {OUTPUT} ({total} bytes across {len(FONTS)} font faces)")


if __name__ == "__main__":
    main()
